TIME_RULE = (
    "怎么体现时间（重要）：① 不要直接报时间，别说「现在晚上十点了」这种话，"
    "要用自然的方式带出来——深夜犯困催睡觉、中午问吃没吃饭、早上惊讶对方起这么早、"
    "上午上课回得慢。② 不是每句都要提时间，只在自然的时候提一句。"
    "③ 作息要符合这个人的习惯：困了就说困，不想聊就短回。"
)

TIME_RULE_TRAINING = (
    "怎么体现时间（重要）：① 不要直接报时间，别说「现在晚上十点了」这种话，"
    "要用自然的方式带出来——深夜犯困催睡觉、中午问吃没吃饭、早上惊讶对方起这么早、"
    "白天在军训所以回得慢。② 不是每句都要提时间，只在自然的时候提一句。"
    "③ 你现在**整天在军训，还没有开始上课**：累、腿酸、晒黑、早起是你的日常，"
    "不要说自己在上课、在教室、在机房。"
)


def period_of(hour, table=None):
    table = table or PERIODS
    name, hint = table[0][1], table[0][2]
    for start, label, detail in table:
        if hour >= start:
            name, hint = label, detail
    return name, hint


def time_hint(now=None, night_owl=False, phase="term"):
    """phase: training（军训）/ preterm（军训完还没开课）/ term（在上课）/ break（假期）"""
    now = now or globals()["now"]()
    table = PERIODS
    if phase == "training":
        table = PERIODS_TRAINING
    elif phase in ("break", "preterm"):
        table = PERIODS_BREAK
    name, hint = period_of(now.hour, table)
    hint = NIGHT_HINTS.get(name, {}).get(bool(night_owl), hint)
    weekday = WEEKDAYS[now.weekday()]
    is_weekend = now.weekday() >= 5
    text = "现在是 %d 月 %d 日 星期%s %02d:%02d（%s）。%s。" % (
        now.month,
        now.day,
        weekday,
        now.hour,
        now.minute,
        name,
        hint,
    )
    if is_weekend:
        if phase == "training":
            text += " 军训期间周末也没有课，一般照常出操或者整理内务。"
        else:
            text += " 今天是周末，不用上课，作息可以松散一点。"
    return {
        "label": name,
        "weekday": weekday,
        "text": text,
        "rule": TIME_RULE_TRAINING if phase == "training" else TIME_RULE,
    }


def stage_hint(now=None, background=""):
    """根据现在的日期和人物背景，推断她处在什么人生阶段。

    返回 (阶段名, 细节描述)；推断不出来就返回 ("", "")。
    """
    now = now or globals()["now"]()
    month, day = now.month, now.day
    blob = background or ""
    is_freshman = any(key in blob for key in ("大一", "新生", "刚高中毕业", "军训"))

    if is_freshman and month == 9 and day <= 26:
        return (
            "刚开学，正在军训（一般 2-3 周）",
            "军训日常：早上五六点就得起来出操，白天站军姿、走方阵、练军体拳、拉歌，"
            "晚上整理内务、写军训心得。会很累、腿酸、晒黑，会吐槽教官严、抱怨天气热。"
            "对方来找你时，你可能刚训完、瘫着不想动，或者急着去集合。",
        )
    if is_freshman and month == 9:
        return (
            "军训刚结束，开始正式上课",
            "刚上大学的课，会聊选课、新同学、宿舍、社团招新，还在适应大学节奏。",
        )
    if is_freshman and month == 10:
        return ("已经正式上课一阵子了", "适应了大学生活，聊上课、作业、社团、宿舍关系。")
    if month in (12, 1):
        return ("期末周", "在复习、赶作业、准备考试，会抱怨熬夜和背书。")
    if month in (2, 3):
        return ("寒假末尾或刚开学", "带着假期的懒散，会聊开学、收拾行李、返校。")
    if month == 6:
        return ("学期末", "准备期末考，或者已经在想暑假怎么过。")
    if month in (7, 8):
        return ("暑假", "在家闲着、打游戏、出去玩，作息很乱，白天睡到很晚。")
    return ("", "")
