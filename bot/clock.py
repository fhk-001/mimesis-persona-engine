"""现实时间与人生阶段感知。

让模型知道"现在几点、星期几、处在什么阶段"，从而像真人一样有生活节奏：
深夜会困会劝人睡觉、中午会提吃饭、早上会惊讶对方起得早；
大一新生九月在军训、十二月在期末周，而不是永远停在语料里的那几天。
"""

from __future__ import annotations

from datetime import datetime

WEEKDAYS = "一二三四五六日"


def now():
    """当前时间。抽成函数是为了方便测试时替换成指定时间点。"""
    return datetime.now()

